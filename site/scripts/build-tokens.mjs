import { readFile, mkdir, writeFile } from 'node:fs/promises';
const source = new URL('../../design/tokens/tokens.json', import.meta.url);
const target = new URL('../src/styles/tokens.css', import.meta.url);
const tokens = JSON.parse(await readFile(source, 'utf8'));
const declarations = [];
const kebab = (key) => key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
function visit(node, path = []) {
  if ('$value' in node) {
    const name = `--${path.map(kebab).join('-')}`;
    if (node.$type === 'typography') {
      for (const [key, value] of Object.entries(node.$value)) {
        const formatted = key === 'fontFamily'
          ? (value[0] === 'Newsreader' ? 'var(--font-newsreader), Georgia, serif' : 'var(--font-hanken), system-ui, sans-serif')
          : value;
        declarations.push(`  ${name}-${kebab(key)}: ${formatted};`);
      }
      const sizes = node.$extensions?.['kanlungan.fontSize'];
      if (sizes) for (const [device, value] of Object.entries(sizes)) declarations.push(`  ${name}-font-size-${device}: ${value};`);
    } else {
      const value = node.$type === 'cubicBezier' ? `cubic-bezier(${node.$value.join(', ')})` : node.$value;
      declarations.push(`  ${name}: ${value};`);
    }
    return;
  }
  for (const [key, child] of Object.entries(node)) if (!key.startsWith('$')) visit(child, [...path, key]);
}
visit(tokens);
await mkdir(new URL('../src/styles/', import.meta.url), { recursive: true });
await writeFile(target, `/* Generated by scripts/build-tokens.mjs from design/tokens/tokens.json. */\n:root {\n${declarations.join('\n')}\n}\n`);
console.log(`Generated ${declarations.length} CSS custom properties.`);
